CREATE TABLE IF NOT EXISTS travel_accounts (
 owner_id BIGINT UNSIGNED PRIMARY KEY,
 available INT UNSIGNED NOT NULL DEFAULT 1,
 reserved INT UNSIGNED NOT NULL DEFAULT 0,
 used INT UNSIGNED NOT NULL DEFAULT 0,
 profile JSON,
 FOREIGN KEY (owner_id) REFERENCES osint_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS travel_orders (
 id CHAR(32) CHARACTER SET ascii PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(40) NOT NULL,
 amount_fen INT UNSIGNED NOT NULL,
 credits INT UNSIGNED NOT NULL,
 status VARCHAR(12) NOT NULL,
 FOREIGN KEY (owner_id) REFERENCES travel_accounts(owner_id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS travel_requests (
 run_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 request_key VARBINARY(128) NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 payload JSON NOT NULL,
 credit_state VARCHAR(10) NOT NULL,
 UNIQUE KEY (owner_id,request_key),
 FOREIGN KEY (run_id) REFERENCES osint_runs(id) ON DELETE CASCADE,
 FOREIGN KEY (owner_id) REFERENCES travel_accounts(owner_id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS travel_attachments (
 id CHAR(32) CHARACTER SET ascii PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 content MEDIUMBLOB NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_id) REFERENCES osint_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
